"""
Режими за дължина на поста — избират се ИЗРИЧНО от човека (REPL `/mode`, TUI `/mode`, CLI
`--mode`), никога от модел. Целта: от един кратък бриф ("едно изречение") да се получи или
къс, или стандартен, или наистина дълъг пост — по избор, не по случайност на модела.

Диапазоните са изведени от практиката за LinkedIn ангажираност (публични анализи на реални
постове, август 2026 — виж research-plan-11-text-quality.md за критиката на предишното
единствено правило "60-150 думи", осреднено грешно от две различни популации):

  - Постовете под ~500 знака (≈ до 90 думи) вършат работа само като кратка, завършена мисъл
    сама по себе си — "hot take"/съобщение, не тийзър към нещо друго.
  - "Сладката точка" за коментари/споделяния е ~1200-1900 знака (≈150-300 думи) — затова
    "Фокус" (по подразбиране) НЕ пипа корпусното правило от knowledge/voice/tone.md, което
    вече цели тази зона.
  - Постове с реално съдържание (истории, поуки, поредица от факти) над ~400 думи получават
    забележимо повече коментари в анализите — "Панорама" се цели там, близо до горния таван
    от 3000 знака на LinkedIn, по изрична потребителска инструкция ("наистина дълги").

Имената са нарочно от фотографията, не буквално "къс/среден/дълъг" — една скàла за размер на
кадъра: Кадър (близък, един момент) → Фокус (стандартна композиция) → Панорама (широк план).
"""

from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class PostMode:
    key: str
    label: str
    words_min: int | None  # None = не пипа диапазона от корпуса (knowledge/voice/tone.md)
    words_max: int | None
    instruction: str  # добавъчен блок към системния промпт на Писателя; "" = нищо добавъчно


MODES: dict[str, PostMode] = {
    "kadar": PostMode(
        key="kadar",
        label="Кадър",
        words_min=40,
        words_max=90,
        instruction=(
            "РЕЖИМ 'Кадър' — избран изрично от човека за ТОЗИ пост, замества диапазона по "
            "подразбиране: 40-90 думи. Една идея, без странични линии — LinkedIn показва само "
            "първите ~40 думи преди 'виж повече' и тук горе-долу ЦЕЛИЯТ пост е в тази зона, "
            "затова той трябва да е завършена мисъл сам по себе си, не тийзър към нещо извън "
            "себе си. Отварящият факт от плана по-долу остава задължителен."
        ),
    ),
    "fokus": PostMode(
        key="fokus",
        label="Фокус",
        words_min=None,
        words_max=None,
        instruction="",
    ),
    "panorama": PostMode(
        key="panorama",
        label="Панорама",
        words_min=400,
        words_max=650,
        instruction=(
            "РЕЖИМ 'Панорама' — избран изрично от човека за ТОЗИ пост, замества диапазона по "
            "подразбиране: 400-650 думи, близо до горната граница на LinkedIn (3000 знака). "
            "Разгърни повода докрай — контекст, ход на събитието, конкретни имена/числа/цитати "
            "от брифа и източниците, поука или следваща стъпка накрая. Всяко изречение пак "
            "трябва да носи факт (виж 'Плътност' по-горе) — дължината идва от повече РЕАЛНО "
            "съдържание, не от повторение на едно и също с други думи или общи изречения."
        ),
    ),
}

DEFAULT_MODE = "fokus"

# Приема и български, и кратки английски синоними — човек пише каквото му е под ръка.
ALIASES: dict[str, str] = {
    "кадър": "kadar", "kadar": "kadar", "къс": "kadar", "кратък": "kadar", "кратко": "kadar",
    "short": "kadar", "s": "kadar",
    "фокус": "fokus", "fokus": "fokus", "focus": "fokus", "среден": "fokus", "стандарт": "fokus",
    "default": "fokus", "d": "fokus",
    "панорама": "panorama", "panorama": "panorama", "дълъг": "panorama", "дълго": "panorama",
    "long": "panorama", "l": "panorama",
}


def resolve_mode(raw: str | None) -> str | None:
    """Разпознава свободен текст ('кадър', 'long', 'ФОКУС'...) → ключ на режим. None = непознат текст."""
    if not raw:
        return None
    return ALIASES.get(raw.strip().lower())


def get_mode(key: str | None) -> PostMode:
    """Връща PostMode по ключ; непознат/липсващ ключ пада безопасно на подразбиращия се ('фокус')."""
    return MODES.get(key or DEFAULT_MODE, MODES[DEFAULT_MODE])


def mode_list_text() -> str:
    """Едноредово изброяване за help текстове/грешки — 'Кадър (40-90 думи), Фокус (...), ...'."""
    parts = []
    for m in MODES.values():
        span = f"{m.words_min}-{m.words_max} думи" if m.words_min else "по преценка на корпуса"
        parts.append(f"{m.label} ({span})")
    return " · ".join(parts)
